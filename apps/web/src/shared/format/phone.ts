/**
 * 联系电话校验：手机号必须为 11 位；固定电话允许区号、分机和常见分隔符。
 * 空值是否允许由调用方决定，本函数只负责格式判断。
 */
export function 联系电话错误(值: unknown): string {
  const 文本值 = String(值 ?? "").trim();
  if (!文本值) return "";
  const 纯数字 = 文本值.replace(/\D+/g, "");
  // 以 1 开头的纯数字按手机号处理，超过或不足 11 位都不允许保存。
  if (/^1\d*$/.test(纯数字) && !/[+\-()\s]/.test(文本值)) {
    return /^1\d{10}$/.test(纯数字) ? "" : "手机号应为 11 位数字。";
  }
  if (/^0\d{2,3}-?\d{7,8}(?:-\d{1,6})?$/.test(文本值)) return "";
  if (/^[0-9+\-()\s]{6,24}$/.test(文本值)) return "";
  return "联系电话格式不正确，请填写 11 位手机号或带区号的固定电话。";
}
