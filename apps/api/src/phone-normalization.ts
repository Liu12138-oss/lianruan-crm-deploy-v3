/** 统一联系电话：仅保留数字，并将中国大陆区号 0086/86 归一为本地 11 位号码。 */
export function 规范化联系电话(值: unknown): string {
  const 数字 = String(值 ?? "").replace(/[^0-9]+/g, "");
  if (/^0086[0-9]{11}$/.test(数字)) return 数字.slice(4);
  if (/^86[0-9]{11}$/.test(数字)) return 数字.slice(2);
  return 数字;
}

/**
 * 校验联系电话格式：手机号必须是 11 位；固定电话允许区号、分机和常见分隔符。
 * 返回空字符串表示通过，否则返回可直接展示给用户的中文错误。
 */
export function 校验联系电话格式(值: unknown): string {
  const 文本值 = String(值 ?? "").trim();
  if (!文本值) return "";
  const 纯数字 = 文本值.replace(/[^0-9]+/g, "");
  if (/^1[0-9]*$/.test(纯数字) && !/[+\-()\s]/.test(文本值)) {
    return /^1[0-9]{10}$/.test(纯数字) ? "" : "手机号应为 11 位数字。";
  }
  if (/^0[0-9]{2,3}-?[0-9]{7,8}(?:-[0-9]{1,6})?$/.test(文本值)) return "";
  if (/^[0-9+\-()\s]{6,24}$/.test(文本值)) return "";
  return "联系电话格式不正确，请填写 11 位手机号或带区号的固定电话。";
}
