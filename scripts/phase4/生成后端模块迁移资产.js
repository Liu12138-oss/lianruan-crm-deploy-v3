function 当前时间() {
  return new Date().toISOString();
}

function 写文本(相对文件, 内容) {
  const 文件 = path.join(项目根目录, 相对文件);
  fs.mkdirSync(path.dirname(文件), { recursive: true });
  fs.writeFileSync(文件, 内容);
}

function 写数据(相对文件, 数据) {
  写文本(相对文件, `${JSON.stringify(数据, null, 2)}\n`);
}

function 表格值(值) {
  return String(值 ?? '').replace(/\|/g, '｜').replace(/\r?\n/g, '<br>');
}

function 表格行(列集合) {
  return `| ${列集合.map(表格值).join(' | ')} |`;
}

function 表格文本值(值) {
  const 文本 = String(值 ?? '');
  return /[",\r\n]/.test(文本) ? `"${文本.replace(/"/g, '""')}"` : 文本;
}

function 表格文本(行集合) {
  return `${行集合.map(行 => 行.map(表格文本值).join(',')).join('\n')}\n`;
}

function 新模块(路由) {
  const 路径 = 路由.path;
  if (路径.startsWith('/api/mobile')) return '移动端';
  if (路径.includes('/mock/') || 路径.startsWith('/api/open') || 路径.startsWith('/api/open-api') || 路径.startsWith('/api/notifications') || 路径.startsWith('/api/company-search')) return '开放接口';
  if (路径.startsWith('/api/auth') || 路径.startsWith('/api/sso') || 路径.startsWith('/api/oauth')) return '认证';
  if (路径.startsWith('/api/users') || 路径.startsWith('/api/admin/accounts')) return '账号';
  if (路径.startsWith('/api/channel') || 路径.startsWith('/api/partners') || 路径.startsWith('/api/partner-profile-products') || 路径.startsWith('/api/dashboard')) return '渠道';
  if (路径.startsWith('/api/registrations')) return '报备';
  if (路径.startsWith('/api/opportunities')) return '商机';
  if (路径.startsWith('/api/quotes') || 路径.startsWith('/api/ipg')) return '报价';
  if (路径.startsWith('/api/orders')) return '订单';
  if (路径.startsWith('/api/pending-approvals')) return '审批';
  if (路径.startsWith('/api/audit-logs')) return '审计';
  if (路径.startsWith('/api/import') || 路径.startsWith('/api/export')) return '导入导出';
  if (路径.startsWith('/api/workload') || 路径.startsWith('/api/meta') || 路径.startsWith('/api/product') || 路径.startsWith('/api/categories') || 路径.startsWith('/api/modules') || 路径.startsWith('/api/features') || 路径.startsWith('/api/hardware') || 路径.startsWith('/api/packages')) return '产品';
  return '待确认';
}

function 下一行(全部路由, 当前路由) {
  return 全部路由.map(路由 => 路由.sourceLine).filter(行号 => 行号 > 当前路由.sourceLine).sort((甲, 乙) => 甲 - 乙)[0] || 当前路由.sourceLine + 160;
}

function 路由片段(源码行集合, 全部路由, 路由) {
  return 源码行集合.slice(路由.sourceLine - 1, Math.min(源码行集合.length, 下一行(全部路由, 路由) - 1)).join('\n');
}

function 有基线风险(路由, 关键词) {
  return (路由.risks || []).some(风险 => 风险.includes(关键词));
}

function 集合读接口(路由) {
  if (路由.method !== 'GET') return false;
  if (路由.path.includes('/:id') || /\/:userId$/.test(路由.path)) return false;
  return /(registrations|opportunities|quotes|orders|partners|users|products|audit-logs|notifications|clients|logs|categories|modules|features|hardware|packages|pending-approvals|channel-targets|channel-visits)/.test(路由.path);
}

function 高风险(路由, 片段) {
  const 风险 = [];
  const 证据 = [];
  if (有基线风险(路由, '读取操作者') || /req\.(body|query|headers)[\s\S]{0,220}(operatorId|operatorName|operatorRole|userId|userRole|role|region|partnerId|createdBy)/.test(片段)) {
    风险.push('信任前端身份');
    证据.push('从请求体、查询参数或请求头读取操作者、角色、区域或渠道范围');
  }
  if (有基线风险(路由, '强制分页或上限') || (集合读接口(路由) && !/pageSize|limit|offset|page/.test(片段))) {
    风险.push('无分页');
    证据.push('阶段0标记或路由片段未发现强制分页、偏移量或最大条数');
  }
  if (/(let|const)\s+list\s*=\s*(db\.|Array\.isArray\(db\.)/.test(片段) || /(db\.[A-Za-z0-9_]+|\(db\.[^)]+\)|Array\.isArray\(db\.[^)]+\))[\s\S]{0,140}\.(filter|map|find|findIndex|slice|sort|flatMap)\s*\(/.test(片段) || /Object\.values\(/.test(片段) || (/handleMobileV2(List|Detail|Events)|scopeOpenApi|filterOpenApi/.test(片段) && /(registrations|opportunities|quotes|orders|partners|users|products|audit|events)/.test(路由.path))) {
    风险.push('内存全量扫描');
    证据.push('路由或适配处理依赖旧全量内存集合的查找、过滤、映射或聚合');
  }
  if (有基线风险(路由, '导入导出') || 路由.path.includes('/import') || 路由.path.includes('/export') || /XLSX|upload\.single|readFileSync|writeFileSync|appendFileSync|createWriteStream/.test(片段)) {
    风险.push('同步导入导出');
    证据.push('涉及文件读取、表格解析、导出生成或同步日志文件读取');
  }
  if (/res\.json\(\{\s*user:\s*db\.users\[0\]/.test(片段) || /normalizeOpenApi(List|Record)\('users'/.test(片段) || /appSecret/.test(片段) || (/res\.json[\s\S]{0,500}(password|secret|accessToken|refreshToken|token)/.test(片段) && !路由.path.includes('/auth/login') && !路由.path.includes('/auth/token'))) {
    风险.push('敏感字段返回');
    证据.push('响应片段可能返回密码、密钥、令牌或包含原始用户对象');
  }
  return {
    风险类别: 风险顺序.filter(名称 => 风险.includes(名称)),
    风险证据: Array.from(new Set(证据)),
  };
}

