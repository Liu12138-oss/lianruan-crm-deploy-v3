function 生成清单(基线, 服务端源码) {
  const 源码行集合 = 服务端源码.split(/\r?\n/);
  return 基线.routes.map(路由 => {
    const 模块 = 新模块(路由);
    const 片段 = 路由片段(源码行集合, 基线.routes, 路由);
    const 风险 = 高风险(路由, 片段);
    const 分层 = 分层归属(路由, 模块);
    return {
      接口编号: 路由.id,
      方法: 路由.method,
      旧路径: 路由.path,
      源码位置: `${路由.sourceFile}:${路由.sourceLine}`,
      阶段0模块: 路由.targetModule,
      新模块: 模块,
      新控制器: 分层.新控制器,
      新服务: 分层.新服务,
      新仓储: 分层.新仓储,
      迁移批次: 模块计划[模块].批次,
      高风险类别: 风险.风险类别,
      风险证据: 风险.风险证据,
      前端调用方: 路由.frontendCallers || [],
      兼容结论: `保留 ${路由.method} ${路由.path} 旧路径，兼容层映射请求、响应和错误后调用新服务。`,
    };
  });
}

function 统计(集合, 取键) {
  return 集合.reduce((结果, 项) => {
    const 键 = 取键(项);
    结果[键] = (结果[键] || 0) + 1;
    return 结果;
  }, {});
}

function 风险统计(清单) {
  const 结果 = Object.fromEntries(风险顺序.map(名称 => [名称, 0]));
  for (const 项 of 清单) for (const 风险 of 项.高风险类别) 结果[风险] += 1;
  return 结果;
}

function 校验(清单, 基线) {
  const 错误 = [];
  if (清单.length !== 257) 错误.push(`迁移清单接口数应为257，实际为${清单.length}`);
  if (清单.length !== 基线.routes.length) 错误.push(`迁移清单接口数与基线不一致，基线为${基线.routes.length}`);
  const 编号集合 = new Set();
  for (const 项 of 清单) {
    if (编号集合.has(项.接口编号)) 错误.push(`接口编号重复：${项.接口编号}`);
    编号集合.add(项.接口编号);
    if (!模块顺序.includes(项.新模块)) 错误.push(`接口${项.接口编号}归属到非法模块：${项.新模块}`);
    if (!项.新控制器 || !项.新服务 || !项.新仓储) 错误.push(`接口${项.接口编号}缺少分层归属`);
  }
  for (const 模块 of 模块顺序) if (!清单.some(项 => 项.新模块 === 模块)) 错误.push(`目标模块没有接口：${模块}`);
  if (错误.length) throw new Error(`阶段4迁移资产生成失败：\n${错误.join('\n')}`);
}

