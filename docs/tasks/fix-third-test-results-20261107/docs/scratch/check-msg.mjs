import { chromium } from "playwright";
const b=await chromium.launch({headless:true});
const c=await b.newContext({baseURL:"http://10.9.86.66",viewport:{width:1600,height:1000}});
const p=await c.newPage();
p.on("console",m=>console.log("CONSOLE",m.type(),m.text()));
p.on("pageerror",e=>console.log("PAGEERROR",e.message));
p.on("response",r=>{if(r.url().includes("/api/messages")||r.status()>=400) console.log("RESP",r.status(),r.url());});
await p.goto("/login",{waitUntil:"domcontentloaded"});
await p.locator('input[autocomplete="username"]').fill("liulonghai");
await p.locator('input[autocomplete="current-password"]').fill("LrCRM@2026!");
await Promise.all([p.waitForURL(u=>!u.pathname.startsWith("/login"),{timeout:30000}),p.getByRole("button",{name:/登\s*录/}).click()]);
await p.waitForTimeout(1000);
console.log("after login",p.url());
await p.goto("/admin/notifications",{waitUntil:"domcontentloaded"});
await p.waitForTimeout(3000);
console.log("after msg",p.url());
console.log("body",(await p.locator("body").innerText()).replace(/\s+/g," ").slice(0,800));
console.log("storage",await p.evaluate(()=>({admin:localStorage.getItem("admin_user_info"),partner:localStorage.getItem("partner_user_info")})));
await b.close();
