function 求和(字段) {
  return 资源预算.reduce((合计, 项) => 合计 + 项[字段], 0);
}

function 校验资源预算() {
  const CPU合计 = 求和('CPU核心数');
  const 内存合计 = 求和('内存GB');
  const 错误 = [];

  if (CPU合计 > 单机资源.CPU核心数 + 2) {
    错误.push(`CPU预算 ${CPU合计} 核心超过可接受超配范围`);
  }
  if (内存合计 > 单机资源.内存GB) {
    错误.push(`内存预算 ${内存合计}GB 超过单机 ${单机资源.内存GB}GB`);
  }
  return 错误;
}

function 输出表格(标题, 列, 数据) {
  console.log(`\n## ${标题}`);
  console.log(`| ${列.join(' | ')} |`);
  console.log(`| ${列.map(() => '---').join(' | ')} |`);
  for (const 行 of 数据) {
    console.log(`| ${列.map((字段) => {
      const 值 = 行[字段];
      return Array.isArray(值) ? 值.join('、') : String(值 ?? '');
    }).join(' | ')} |`);
  }
}

